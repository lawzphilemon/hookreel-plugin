// Usage: node scripts/register-videos.mjs
// Writes src/videos.generated.ts: every videos/*.json (one composition each) and the voiceover
// clips that exist in public/vo/, so the studio never has to probe for missing files.
import fs from "fs";
import path from "path";

const files = fs.existsSync("videos") ? fs.readdirSync("videos").filter((f) => f.endsWith(".json")).sort() : [];
const vo = {};
for (const file of files) {
  const id = file.replace(/\.json$/, "");
  const dir = path.join("public", "vo", id);
  if (!fs.existsSync(dir)) continue;
  for (const clip of fs.readdirSync(dir).filter((f) => /\.(wav|mp3|m4a)$/.test(f)).sort()) {
    const scene = clip.replace(/\.(wav|mp3|m4a)$/, "");
    const words = fs.existsSync(path.join(dir, `${scene}.words.json`)) ? `vo/${id}/${scene}.words.json` : null;
    vo[`${id}/${scene}`] ??= { src: `vo/${id}/${clip}`, words };
  }
}
const lines = [
  "// Generated by scripts/register-videos.mjs. Do not edit; add or change videos/*.json instead.",
  'import type { VideoSpec } from "./schema";',
  ...files.map((f, i) => `import v${i} from "../videos/${f}";`),
  "",
  `export const VIDEOS = [${files.map((_, i) => `v${i}`).join(", ")}] as VideoSpec[];`,
  "",
  "// Recorded voiceover clips: `<video id>/<scene id>` → files in public/.",
  `export const VO_FILES: Record<string, { src: string; words: string | null }> = ${JSON.stringify(vo, null, 2)};`,
  "",
];
fs.writeFileSync(path.join("src", "videos.generated.ts"), lines.join("\n"));
console.log(`Registered ${files.length} video(s): ${files.map((f) => f.replace(".json", "")).join(", ") || "none"}; ${Object.keys(vo).length} voiceover clip(s)`);
